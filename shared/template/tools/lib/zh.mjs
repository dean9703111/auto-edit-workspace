// 繁簡處理：whisper 有時轉成簡體（同一個模型，看聲音），講稿、字幕都是繁體。
//   foldZh(s)    比對用：繁體折成簡體（一個字換一個字，長度不變），「不滿意」和「不满意」就是同一個詞
//   toTrad(s)    顯示用：簡體換回繁體，先處理一字多義的詞（头发→頭髮、干净→乾淨、一只→一隻），其他逐字換
//   hasSimplified(s)  這段文字有沒有簡體字
import { FOLD, S2T } from './zh-table.mjs';

const pairsOf = (s) => { const m = new Map(); for (let i = 0; i + 1 < s.length; i += 2) m.set(s[i], s[i + 1]); return m; };
let fold = null, s2t = null;
const foldMap = () => (fold ??= pairsOf(FOLD));
const s2tMap = () => (s2t ??= pairsOf(S2T));

export const foldZh = (s) => String(s ?? '').replace(/[一-鿿]/g, (c) => foldMap().get(c) ?? c);

