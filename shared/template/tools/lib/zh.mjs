const KEYS = Object.keys(PHRASES).sort((a, b) => b.length - a.length);
const PH_RE = new RegExp(KEYS.join('|'), 'g');
export function toTrad(s) {
  const map = s2tMap();
  const held = [];
  // 詞表先換成占位（U+E000 起），逐字換完再放回去，才不會把詞表的結果又換一次
  const t = String(s ?? '').replace(PH_RE, (w) => { held.push(PHRASES[w]); return String.fromCharCode(0xE000 + held.length - 1); });
  return t.replace(/[一-鿿]/g, (c) => map.get(c) ?? c).replace(/[-]/g, (c) => held[c.charCodeAt(0) - 0xE000]);
}

// 「简体字」：在 S2T 裡、而且本身不是繁體常用字（FOLD 的值）；只拿來判斷，不用很精準
export function hasSimplified(s) {
  const map = s2tMap();
  for (const c of String(s ?? '')) if (map.has(c) && foldMap().get(map.get(c)) === c && !foldMap().has(c)) return true;
  return false;
}
