// 唯讀檢查目前的本機剪輯頁；不儲存任何專案設定。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import puppeteer from 'puppeteer-core';
import { findChrome } from '../shared/template/tools/lib/audit-browser.mjs';

const base = new URL(process.argv[2]);
assert.equal(base.hostname, '127.0.0.1');
const response = await fetch(new URL('/api/design', base));
assert.equal(response.status, 200);
const state = await response.json();
assert.ok(state.previews.length > 0);
const browser = await puppeteer.launch({ executablePath: findChrome(), headless: true });
try {
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.setViewport({ width: 1440, height: 1000 });
  await page.goto(new URL('/framing', base).href);
  await page.waitForSelector('#main:not([hidden])', { timeout: 60000 });
  await page.waitForFunction(() => !!window.framingImage || !!document.querySelector('#video')?.error);
  const speakerSource = await page.evaluate(() => window.framingImage ? 'live-frame' : 'saved-reference');
  await page.waitForSelector('#designPreviews iframe', { timeout: 60000 });
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'editor-live-'));
  await page.hover('#designPreviews .design-preview-stage');
  assert.equal(await page.$eval('#designPreviews .design-preview-stage button', (b) => getComputedStyle(b).backgroundColor), 'rgba(0, 0, 0, 0)');
  const chapterFrame = await (await page.$('#designPreviews iframe')).contentFrame();
  await chapterFrame.waitForFunction(() => window.gsap?.globalTimeline.getChildren(false, false, true).some((t) => !t.paused() && t.time() > 1 && t.time() < 3));
  const hoverScreenshot = path.join(dir, '章節轉場-滑入.png');
  await page.screenshot({ path: hoverScreenshot });
  await page.click('[data-category="custom"]');
  const element = await page.$('#designPreviews iframe');
  await element.scrollIntoView();
  const frame = await element.contentFrame();
  await page.mouse.move(0, 0);
  await frame.waitForFunction(() => window.gsap?.globalTimeline.getChildren(false, false, true).some((t) => t.duration() > 0 && t.paused() && Math.abs(t.time() - (t.duration() - 1.8)) < .01));
  await page.hover('#designPreviews .design-preview-stage');
  assert.equal(await page.$eval('#designPreviews .design-preview-stage button', (b) => getComputedStyle(b).backgroundColor), 'rgba(0, 0, 0, 0)');
  await frame.waitForFunction(() => gsap.globalTimeline.getChildren(false, false, true).some((t) => !t.paused() && t.time() > .1));
  assert.equal(await frame.evaluate(() => gsap.globalTimeline.getChildren(false, false, true).some((t) => t.repeat() === -1)), true);
  await frame.evaluate(() => gsap.globalTimeline.getChildren(false, false, true).forEach((t) => t.timeScale(30)));
  await frame.waitForFunction(() => gsap.globalTimeline.getChildren(false, false, true).some((t) => t.iteration() >= 2 && !t.paused()));
  await frame.evaluate(() => gsap.globalTimeline.getChildren(false, false, true).forEach((t) => t.timeScale(1)));
  await page.mouse.move(0, 0);
  await frame.waitForFunction(() => gsap.globalTimeline.getChildren(false, false, true).some((t) => t.paused() && Math.abs(t.time() - (t.duration() - 1.8)) < .01));
  const screenshot = path.join(dir, '構圖動畫.png');
  await page.screenshot({ path: screenshot });
  await page.click('[data-kind="side"]');
  const sideElement = await page.waitForSelector('#designBgComposite iframe');
  await sideElement.scrollIntoView();
  const side = await sideElement.contentFrame();
  await side.waitForFunction(() => window.gsap?.globalTimeline.getChildren(true, false, true).some((t) => t.paused() && Math.abs(t.time() - 3.2) < .01));
  if (speakerSource === 'live-frame') await side.waitForFunction(() => document.querySelector('#footage img')?.src.startsWith('data:image/jpeg;base64,'));
  await side.waitForFunction(() => { const img = document.querySelector('#footage img'); return img?.complete && img.naturalWidth > 0; });
  const shift = await side.evaluate(() => Number(gsap.getProperty('#footage', 'x')));
  assert.equal(shift, 480, '講者沿用成片側邊欄的右移位置，避免只露出半邊');
  const sideScreenshot = path.join(dir, '側邊欄完成預覽.png');
  await page.screenshot({ path: sideScreenshot });
  await page.click('.design-bg-enlarge');
  assert.equal(await page.$eval('.design-bg-enlarge', (b) => getComputedStyle(b).backgroundColor), 'rgba(0, 0, 0, 0)');
  await page.waitForSelector('#designDialog[open]');
  const enlarged = await (await page.$('#designDialogStage iframe')).contentFrame();
  await page.hover('#designDialogStage');
  await enlarged.waitForFunction(() => window.gsap?.globalTimeline.getChildren(false, false, true).some((t) => !t.paused() && t.time() > .1));
  await page.hover('#closeDesignDialog');
  await enlarged.waitForFunction(() => window.gsap?.globalTimeline.getChildren(true, false, true).some((t) => t.paused() && Math.abs(t.time() - 3.2) < .01));
  await page.click('#closeDesignDialog');
  await page.setViewport({ width: 390, height: 844 });
  await page.$eval('.design-bg-preview', (el) => el.scrollIntoView({ block: 'center' }));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const mobileScreenshot = path.join(dir, '側邊欄完成預覽-手機.png');
  await page.screenshot({ path: mobileScreenshot });
  assert.deepEqual(errors, []);
  assert.ok(await page.$('[data-variant="original"]'));
  console.log(JSON.stringify({ url: new URL('/framing', base).href, apiStatus: response.status, previews: state.previews.length, hoverOverlayTransparent: true, defaultStill: true, loopOnHover: true, returnToStillOnLeave: true, originalAvailable: true, sideCompletedAt: 3.2, sideSpeakerShift: shift, speakerSource, pageErrors: errors.length, hoverScreenshot, screenshot, sideScreenshot, mobileScreenshot }));
} finally { await browser.close(); }
