async function dragFiles(page, selector, type, files) {
  return page.evaluate(({ selector, type, files }) => {
    const transfer = new DataTransfer();
    for (const file of files) {
      const bytes = file.size ? new Uint8Array(file.size) : Uint8Array.from(atob(file.data || ''), (c) => c.charCodeAt(0));
      transfer.items.add(new File([bytes], file.name, { type: file.type }));
    }
    const event = new DragEvent(type, { bubbles: true, cancelable: true, dataTransfer: transfer });
    const target = document.querySelector(selector);
    target.dispatchEvent(event);
    return { prevented: event.defaultPrevented, highlighted: target.closest('label')?.classList.contains('is-dragover') };
  }, { selector, type, files });
}
